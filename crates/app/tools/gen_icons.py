#!/usr/bin/env python3
"""Generate icon data: python3 crates/app/tools/gen_icons.py /path/to/farm_sprites_icons.dart
Run cargo fmt --all afterwards. The Flutter source is only read, never modified.
"""
import re
import sys
from pathlib import Path

source = Path(sys.argv[1]).read_text(encoding="utf-8")
body = source.split('const _icons =', 1)[1].split('final _iconCache', 1)[0]
pattern = re.compile(r"FarmIcon\.(\w+):\s*\(\s*\[(.*?)\],\s*\{(.*?)\},\s*\)", re.S)
icons = []
for name, rows_text, palette_text in pattern.findall(body):
    rows = re.findall(r"'([^']*)'", rows_text)
    palette = re.findall(r"'(.)':\s*(0x[0-9a-fA-F]+)", palette_text)
    if len(rows) != 10 or any(len(row) != 10 for row in rows):
        raise ValueError(f"Invalid dimensions for {name}")
    if set(''.join(rows)) - {'.'} - {key for key, _ in palette}:
        raise ValueError(f"Unmapped character in {name}")
    icons.append((name, rows, palette))
enum_body = source.split('enum FarmIcon {', 1)[1].split('}', 1)[0]
enum_names = re.findall(r'^\s*(\w+),', enum_body, re.M)
if [item[0] for item in icons] != enum_names:
    raise ValueError('Icon map and enum do not match')

out = Path(__file__).resolve().parents[1] / 'src/farm/icons'
for group in range((len(icons) + 6) // 7):
    lines = ['// Generated by crates/app/tools/gen_icons.py; do not edit.',
             '// Ported from clodfarm (MIT), via farm_sprites_icons.dart.',
             'use super::IconData;', '']
    for name, rows, palette in icons[group * 7:(group + 1) * 7]:
        lines += [f'pub(super) const {name.upper()}: IconData = IconData {{', '    rows: &[']
        lines += [f'        "{row}",' for row in rows]
        lines += ['    ],', '    palette: &[']
        lines += [f"        (b'{key}', {value.lower()})," for key, value in palette]
        lines += ['    ],', '};', '']
    (out / f'data_{group + 1}.rs').write_text('\n'.join(lines), encoding='utf-8')
print(f'Generated {len(icons)} icons')
for name, rows, _ in icons:
    print(name, sum(c != '.' for row in rows for c in row))
